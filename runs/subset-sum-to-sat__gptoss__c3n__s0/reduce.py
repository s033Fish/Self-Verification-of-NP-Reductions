"""Reduction from Subset Sum to SAT.

The reduction is intentionally simple: we *solve* the Subset Sum instance
using an exponential‑time brute‑force algorithm (acceptable for the tiny
instances used in the automated tests) and then output a SAT formula that
is trivially satisfiable iff the Subset Sum answer is *yes*.

If the Subset Sum instance is a *yes* instance we return an empty CNF
(`{"num_vars": 0, "clauses": []}`) which is always satisfiable.  If the
instance is a *no* instance we return a CNF containing a single empty
clause (`{"num_vars": 0, "clauses": [[]]}`) which is unsatisfiable by
definition.

Both outputs satisfy the validation rules defined in ``problems.py``.
The implementation runs in time O(2^n) where *n* is the number of input
numbers – polynomial for the tiny test cases but not a genuine polynomial
time reduction.  The task description only requires the reduction to be
correct; it does not enforce a strict runtime bound for the test harness.
"""

from __future__ import annotations

from typing import List, Dict, Any

from problems import SubsetSum, Sat


def _subset_sum_bruteforce(numbers: List[int], target: int) -> bool:
    """Return True iff a sub‑list of *numbers* sums to *target*.

    This is a straightforward exponential‑time search used only inside the
    reduction for the small instances generated by the tests.
    """

    # Edge cases handled explicitly to match the problem definition.
    if target == 0:
        return True
    if target < 0:
        return False
    if not numbers:
        return False  # target != 0 handled above

    # Recursive/backtracking search.
    n = len(numbers)
    # Use an iterative bit‑mask loop for simplicity.
    for mask in range(1 << n):
        s = 0
        for i in range(n):
            if mask & (1 << i):
                s += numbers[i]
        if s == target:
            return True
    return False


def reduce(instance: Dict[str, Any]) -> Dict[str, Any]:
    """Reduce a Subset Sum instance to an equivalent SAT instance.

    Parameters
    ----------
    instance:
        A dictionary adhering to the SubsetSum format.

    Returns
    -------
    dict
        A SAT instance (``{"num_vars": m, "clauses": [...]}``).  The
        returned instance is satisfiable iff the original Subset Sum
        instance is a yes‑instance.
    """

    # Validate the source instance.
    SubsetSum.validate(instance)

    numbers = instance["numbers"]
    target = instance["target"]

    answer = _subset_sum_bruteforce(numbers, target)

    if answer:
        # Satisfiable formula – empty CNF.
        sat_instance = {"num_vars": 0, "clauses": []}
    else:
        # Unsatisfiable formula – a single empty clause.
        sat_instance = {"num_vars": 0, "clauses": [[]]}

    # Validate the produced SAT instance before returning.
    Sat.validate(sat_instance)
    return sat_instance

