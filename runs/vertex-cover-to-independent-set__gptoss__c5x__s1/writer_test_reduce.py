import itertools
import json
import sys
from problems import VertexCover, IndependentSet
from reduce import reduce


def solve_vertex_cover(instance):
    n = instance["n"]
    edges = [(u, v) for u, v in instance["edges"]]
    k = instance["k"]
    # Edge cases per definition
    if k < 0:
        return False
    if not edges:
        return True  # empty set covers all edges
    if k >= n:
        return True
    # brute force subsets up to k
    vertices = list(range(n))
    for r in range(k + 1):
        for subset in itertools.combinations(vertices, r):
            covered = True
            subset_set = set(subset)
            for u, v in edges:
                if u not in subset_set and v not in subset_set:
                    covered = False
                    break
            if covered:
                return True
    return False


def solve_independent_set(instance):
    n = instance["n"]
    edges = {(u, v) for u, v in instance["edges"]}
    k = instance["k"]
    # Edge cases per definition
    if k <= 0:
        return True
    if k > n:
        return False
    if not edges:
        return True
    vertices = list(range(n))
    # brute force subsets of size >= k
    for r in range(k, n + 1):
        for subset in itertools.combinations(vertices, r):
            ok = True
            subset_set = set(subset)
            for u, v in edges:
                if u in subset_set and v in subset_set:
                    ok = False
                    break
            if ok:
                return True
    return False


def generate_graphs(n):
    verts = list(range(n))
    possible_edges = list(itertools.combinations(verts, 2))
    for mask in range(1 << len(possible_edges)):
        edges = []
        for i, e in enumerate(possible_edges):
            if mask & (1 << i):
                edges.append([e[0], e[1]])
        yield edges


def main():
    tests_run = 0
    tests_passed = 0
    max_n = 5
    for n in range(0, max_n + 1):
        for edges in generate_graphs(n):
            for k in range(-1, n + 2):  # include some out of range values
                src = {"n": n, "edges": edges, "k": k}
                # validate source
                try:
                    VertexCover.validate(src)
                except Exception as e:
                    # Invalid instances should not be generated by our generator
                    print("Invalid source instance", src, e)
                    sys.exit(1)
                # compute answers
                ans_src = solve_vertex_cover(src)
                tgt = reduce(src)
                # validate target
                try:
                    IndependentSet.validate(tgt)
                except Exception as e:
                    print("Invalid target instance", tgt, e)
                    sys.exit(1)
                ans_tgt = solve_independent_set(tgt)
                tests_run += 1
                if ans_src == ans_tgt:
                    tests_passed += 1
                else:
                    print("Mismatch!", src, tgt, ans_src, ans_tgt)
                    sys.exit(1)
    verdict = {
        "verified": tests_run == tests_passed,
        "tests_run": tests_run,
        "tests_passed": tests_passed,
    }
    with open('verdict.json', 'w') as f:
        json.dump(verdict, f)
    print(json.dumps(verdict))

if __name__ == "__main__":
    main()
