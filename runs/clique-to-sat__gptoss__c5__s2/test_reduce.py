"""Test suite for the Clique → SAT reduction.

The repository provides only the problem definitions and the reduction
implementation.  To verify that the reduction is correct we implement
straight‑forward brute‑force solvers for both problems and compare the
answers on a collection of small instances.

For each generated instance we:
1. Validate the instance using the problem's ``validate`` method.
2. Compute the correct answer with the brute‑force solver.
3. Reduce the instance to SAT via ``reduce``.
4. Validate the produced SAT instance.
5. Compute the SAT answer with its brute‑force solver.
6. Check that the two answers match.

The script records how many tests were executed and how many passed and
writes a ``verdict.json`` file in the repository root as required by the
task description.
"""

from __future__ import annotations

import itertools
import json
import sys
from typing import List, Dict, Any

# Import the problem definitions and the reduction implementation.
from problems import Clique, Sat
from reduce import reduce as reduce_instance


def brute_force_clique(instance: Dict[str, Any]) -> bool:
    """Return True iff the graph has a clique of size at least ``k``.

    The instance is assumed to be validated already.
    """
    n = instance["n"]
    edges = {frozenset(e) for e in instance["edges"]}
    k = instance["k"]

    # Edge cases directly from the problem statement.
    if k <= 0:
        return True
    if k == 1:
        return n >= 1
    if k > n:
        return False

    vertices = list(range(n))
    for size in range(k, n + 1):
        for subset in itertools.combinations(vertices, size):
            if all(frozenset((u, v)) in edges for u, v in itertools.combinations(subset, 2)):
                return True
    return False


def brute_force_sat(instance: Dict[str, Any]) -> bool:
    """Return True iff the CNF formula is satisfiable.

    A naïve exhaustive search over all assignments is sufficient for the
    tiny instances generated by the tests.
    """
    m = instance["num_vars"]
    clauses: List[List[int]] = instance["clauses"]

    if not clauses:
        return True
    if any(len(c) == 0 for c in clauses):
        return False

    for bits in range(1 << m):
        assignment = [(bits >> i) & 1 == 1 for i in range(m)]
        satisfied = True
        for clause in clauses:
            clause_sat = False
            for lit in clause:
                var = abs(lit) - 1
                val = assignment[var]
                if (lit > 0 and val) or (lit < 0 and not val):
                    clause_sat = True
                    break
            if not clause_sat:
                satisfied = False
                break
        if satisfied:
            return True
    return False


def generate_graph_instances(max_n: int) -> List[Dict[str, Any]]:
    """Generate all possible graph instances with up to ``max_n`` vertices.

    For each number of vertices ``n`` we enumerate every possible edge set
    (undirected, no self‑loops) and a range of ``k`` values covering the edge
    cases.
    """
    instances: List[Dict[str, Any]] = []
    for n in range(0, max_n + 1):
        possible_edges = [(i, j) for i in range(n) for j in range(i + 1, n)]
        for edge_mask in range(1 << len(possible_edges)):
            edges = []
            for idx, (u, v) in enumerate(possible_edges):
                if (edge_mask >> idx) & 1:
                    edges.append([u, v])
            for k in range(-1, n + 2):
                instances.append({"n": n, "edges": edges, "k": k})
    return instances


def main() -> None:
    # Use n up to 4 to keep SAT brute‑force feasible.
    instances = generate_graph_instances(max_n=4)
    total = len(instances)
    passed = 0

    for idx, inst in enumerate(instances, 1):
        try:
            Clique.validate(inst)
        except Exception as e:
            print(f"Invalid Clique instance at #{idx}: {e}", file=sys.stderr)
            continue
        expected = brute_force_clique(inst)
        sat_inst = reduce_instance(inst)
        try:
            Sat.validate(sat_inst)
        except Exception as e:
            print(f"Reduction produced invalid SAT instance at #{idx}: {e}", file=sys.stderr)
            continue
        actual = brute_force_sat(sat_inst)
        if expected == actual:
            passed += 1
        else:
            print(
                f"Mismatch on instance #{idx}: expected {expected}, got {actual}\n{inst}\n{sat_inst}",
                file=sys.stderr,
            )

    verdict = {
        "verified": passed == total,
        "tests_run": total,
        "tests_passed": passed,
    }
    with open("verdict.json", "w", encoding="utf-8") as f:
        json.dump(verdict, f, indent=2)
    print(json.dumps(verdict, indent=2))

if __name__ == "__main__":
    main()
