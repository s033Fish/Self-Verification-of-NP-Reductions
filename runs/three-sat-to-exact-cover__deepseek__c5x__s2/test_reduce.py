"""Tests for the reduction from ThreeSat to ExactCover.

The script implements brute‑force solvers for both source and target
problems, generates a variety of small random instances, reduces them
using ``reduce.reduce`` and checks that the answers coincide.

If all generated instances pass, ``verdict.json`` is written with
``{"verified": true, "tests_run": N, "tests_passed": N}``.  Otherwise the
verdict reports ``verified: false`` and the numbers of total and passed
tests.
"""

from __future__ import annotations

import json
import random
import sys
from pathlib import Path

import problems
import reduce


def solve_three_sat(instance: dict) -> bool:
    """Brute‑force SAT solver for 3‑SAT instances.

    Returns ``True`` iff the formula is satisfiable.
    """
    m = instance["num_vars"]
    clauses = instance["clauses"]
    for bits in range(1 << m):
        ok = True
        for clause in clauses:
            clause_ok = False
            for lit in clause:
                var = abs(lit) - 1
                val = (bits >> var) & 1
                if (lit > 0 and val) or (lit < 0 and not val):
                    clause_ok = True
                    break
            if not clause_ok:
                ok = False
                break
        if ok:
            return True
    return False


def solve_exact_cover(instance: dict) -> bool:
    """Brute‑force exact‑cover solver using a simple recursive algorithm.

    Suitable for the tiny instances generated by the test harness.
    """
    u = instance["universe_size"]
    sets = [set(s) for s in instance["sets"]]
    target = set(range(u))
    # map element -> list of set indices containing it
    element_to_sets: dict[int, list[int]] = {e: [] for e in target}
    for idx, s in enumerate(sets):
        for e in s:
            element_to_sets[e].append(idx)

    def backtrack(covered: set[int]) -> bool:
        if covered == target:
            return True
        # pick an uncovered element
        e = next(iter(target - covered))
        for idx in element_to_sets[e]:
            s = sets[idx]
            if covered.isdisjoint(s):
                if backtrack(covered | s):
                    return True
        return False

    return backtrack(set())


def random_three_sat(m: int, q: int) -> dict:
    """Generate a random 3‑SAT instance with ``m`` variables and ``q`` clauses.
    Each clause contains three distinct variables with random signs.
    """
    clauses = []
    for _ in range(q):
        vars_ = random.sample(range(1, m + 1), 3) if m >= 3 else []
        clause = [v if random.choice([True, False]) else -v for v in vars_]
        clauses.append(clause)
    return {"num_vars": m, "clauses": clauses}


def main() -> None:
    random.seed(0)
    total = 0
    passed = 0
    for m in range(0, 5):
        for q in range(0, 6):
            for _ in range(20):
                if q > 0 and m < 3:
                    continue
                inst = random_three_sat(m, q)
                try:
                    problems.ThreeSat.validate(inst)
                except Exception as e:
                    print(f"Invalid generated instance: {inst}\n{e}", file=sys.stderr)
                    continue
                red = reduce.reduce(inst)
                try:
                    problems.ExactCover.validate(red)
                except Exception as e:
                    print(f"Reduction produced invalid instance: {red}\n{e}", file=sys.stderr)
                    continue
                ans_src = solve_three_sat(inst)
                ans_tgt = solve_exact_cover(red)
                total += 1
                if ans_src == ans_tgt:
                    passed += 1
                else:
                    print("Mismatch!", file=sys.stderr)
                    print("Source:", json.dumps(inst), file=sys.stderr)
                    print("Reduced:", json.dumps(red), file=sys.stderr)
                    print("src ans", ans_src, "tgt ans", ans_tgt, file=sys.stderr)
    verdict = {
        "verified": passed == total,
        "tests_run": total,
        "tests_passed": passed,
    }
    Path("verdict.json").write_text(json.dumps(verdict, indent=2))
    print(json.dumps(verdict, indent=2))

if __name__ == "__main__":
    main()
