"""Build task directories from the problem library.

For each pair in benchmark/pairs.json this writes

    tasks/<source>-to-<target>/
        task.json                     descriptor read by `workflow generate`
        inputs/problems.py            the two problems, bundled into one file
        inputs/problems_nosolver.py   specs and validate() only (condition c3n)

problems.py is self-contained: it holds base.py, the helper modules the two
problems need and the two problem classes, with the package's relative
imports removed, plus SOURCE and TARGET aliases. Agents see only this file,
never benchmark/. After writing it, the bundle is loaded and checked against
the library, so a bundling bug fails here rather than mid-experiment.

    uv run python -m benchmark.make_task --all              # every pair
    uv run python -m benchmark.make_task three_sat clique   # one pair
    uv run python -m benchmark.make_task --list             # problem keys

problems_nosolver.py is what agents see as problems.py in the no-solver
setting: each problem's docstring and validate(), plus the validation
helpers they call, and nothing else. No is_yes, no generators and no solver
helpers, so an agent that wants to test must write its own solvers from its
own reading of the spec.

Edit the library or pairs.json, then regenerate; never edit tasks/ by hand.
"""

from __future__ import annotations

import argparse
import ast
import importlib.util
import json
import shutil
import sys
from dataclasses import dataclass
from itertools import islice
from pathlib import Path
from types import ModuleType

from benchmark.problems import PROBLEMS, Problem
from workflow.tasks import ReductionTask

BENCHMARK = Path(__file__).resolve().parent
PROBLEMS_DIR = BENCHMARK / "problems"
PAIRS_FILE = BENCHMARK / "pairs.json"
TASKS_DIR = BENCHMARK.parent / "tasks"

# Instances per problem compared between the bundle and the library.
CHECKED_INSTANCES = 300

HEADER = '''"""Problem definitions for this task: {source} -> {target}.

SOURCE = {source_class}: {source}, the problem you reduce FROM.
TARGET = {target_class}: {target}, the problem you reduce TO.

Read the SOURCE and TARGET class docstrings for the exact instance formats,
yes-conditions and edge cases. Instances are plain dicts. Each class has:

    validate(instance)            raise InvalidInstance if malformed
    is_yes(instance)              exact answer; exponential time, so small
                                  instances only
    random_instance(rng, scale)   a random instance (rng is a random.Random)
    enumerate_instances(scale)    every small instance up to that scale
    size(instance)                encoding length of an instance

Other classes and helpers in this file support these two; you can ignore them.
Generated by benchmark/make_task.py from the benchmark's problem library.
"""

from __future__ import annotations
'''

INSTRUCTIONS = (
    "Write a polynomial-time reduction from {source} to {target}. "
    "problems.py defines both problems: SOURCE is {source} and TARGET is "
    "{target}. The SOURCE and TARGET class docstrings give the exact instance "
    "formats, yes-conditions and edge cases."
)


@dataclass(frozen=True)
class Pair:
    source: str
    target: str
    famous: bool
    split: str

    @property
    def task_id(self) -> str:
        return f"{self.source.replace('_', '-')}-to-{self.target.replace('_', '-')}"


# --- pairs.json -----------------------------------------------------------------


def load_pairs(path: Path = PAIRS_FILE) -> list[Pair]:
    raw = json.loads(path.read_text())["pairs"]
    pairs = [Pair(item["source"], item["target"], item["famous"], item["split"]) for item in raw]
    problems = []
    seen = set()
    for pair in pairs:
        for key in (pair.source, pair.target):
            if key not in PROBLEMS:
                problems.append(f"unknown problem {key!r}")
        if pair.source == pair.target:
            problems.append(f"{pair.task_id}: source and target are the same")
        if pair.split not in {"dev", "test"}:
            problems.append(f"{pair.task_id}: split must be 'dev' or 'test'")
        if not isinstance(pair.famous, bool):
            problems.append(f"{pair.task_id}: famous must be true or false")
        if pair.task_id in seen:
            problems.append(f"{pair.task_id}: listed twice")
        seen.add(pair.task_id)
    if problems:
        raise ValueError(f"{path}:\n  " + "\n  ".join(problems))
    return pairs


# --- Bundling -------------------------------------------------------------------


def module_name(problem: type[Problem]) -> str:
    return problem.__module__.rsplit(".", 1)[-1]


def _tree(module: str) -> tuple[str, ast.Module]:
    source = (PROBLEMS_DIR / f"{module}.py").read_text()
    return source, ast.parse(source)


def _relative_imports(tree: ast.Module) -> list[ast.ImportFrom]:
    imports = [n for n in tree.body if isinstance(n, ast.ImportFrom) and n.level > 0]
    for node in imports:
        if node.level != 1 or not node.module:
            raise ValueError("only 'from .module import name' imports can be bundled")
    return imports


def dependency_order(roots: list[str]) -> list[str]:
    """The modules `roots` need, each after everything it imports."""
    order: list[str] = []
    visiting: set[str] = set()

    def visit(module: str) -> None:
        if module in order:
            return
        if module in visiting:
            raise ValueError(f"import cycle through {module}")
        visiting.add(module)
        _, tree = _tree(module)
        for node in _relative_imports(tree):
            assert node.module is not None
            visit(node.module)
        visiting.discard(module)
        order.append(module)

    for root in roots:
        visit(root)
    return order


def _top_level_names(tree: ast.Module) -> set[str]:
    names: set[str] = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            names.update(t.id for t in targets if isinstance(t, ast.Name))
    return names


# Verifier-only information that must not reach agents: the exhaustive test
# scale told one agent exactly how far the hidden verifier checks, and it wrote
# a reduction that was only "polynomial" up to that scale.
HIDDEN_NAMES = ("exhaustive_scale", "check_problem")


def _with_leading_comments(lines: list[str], start: int) -> int:
    """Extend a 1-based start line upward over the comment lines just above it."""
    while start > 1 and lines[start - 2].strip().startswith("#"):
        start -= 1
    return start


def _hidden_lines(source: str, tree: ast.Module) -> set[int]:
    """Line numbers of everything that reveals how the verifier tests."""
    lines = source.splitlines()
    drop: set[int] = set()
    for node in ast.walk(tree):
        hidden = False
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            hidden = any(isinstance(t, ast.Name) and t.id == "exhaustive_scale" for t in targets)
        elif isinstance(node, ast.If):
            hidden = "exhaustive_scale" in (ast.get_source_segment(source, node.test) or "")
        elif isinstance(node, ast.FunctionDef) and node.name == "check_problem":
            hidden = True
        if hidden:
            assert node.end_lineno is not None
            drop.update(range(_with_leading_comments(lines, node.lineno), node.end_lineno + 1))
    return drop


def _strip(source: str, tree: ast.Module) -> str:
    """The module without its docstring, `from __future__`, relative imports
    and verifier-only details (HIDDEN_NAMES)."""
    drop: set[int] = _hidden_lines(source, tree)
    for index, node in enumerate(tree.body):
        is_docstring = (
            index == 0
            and isinstance(node, ast.Expr)
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, str)
        )
        is_bundled_import = isinstance(node, ast.ImportFrom) and (
            node.level > 0 or node.module == "__future__"
        )
        if is_docstring or is_bundled_import:
            assert node.end_lineno is not None
            drop.update(range(node.lineno, node.end_lineno + 1))
    lines = source.splitlines()
    kept = [line for number, line in enumerate(lines, start=1) if number not in drop]
    text = "\n".join(kept).strip("\n")
    return text.replace(
        "Subclasses set `name`,\n    `exhaustive_scale` and a docstring",
        "Subclasses set `name`\n    and a docstring",
    )


def bundle(source: type[Problem], target: type[Problem]) -> str:
    """One self-contained problems.py for this pair."""
    modules = dependency_order([module_name(source), module_name(target)])
    defined: dict[str, str] = {}
    parts = [
        HEADER.format(
            source=source.name,
            target=target.name,
            source_class=source.__name__,
            target_class=target.__name__,
        )
    ]
    for module in modules:
        text, tree = _tree(module)
        for name in _top_level_names(tree) - {"__all__"}:
            if name in defined:
                raise ValueError(
                    f"{name!r} is defined in both {defined[name]}.py and {module}.py; "
                    "rename one so the bundle does not silently overwrite it"
                )
            defined[name] = module
        parts.append(f"# {'-' * 70}\n# From benchmark/problems/{module}.py\n\n{_strip(text, tree)}\n")
    parts.append(
        f"# {'-' * 70}\n\n"
        f"SOURCE = {source.__name__}\n"
        f"TARGET = {target.__name__}\n"
    )
    return "\n\n".join(parts)


def load_bundle(path: Path) -> ModuleType:
    spec = importlib.util.spec_from_file_location(f"_bundle_{path.parent.parent.name}", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module  # dataclasses and typing look modules up here
    try:
        spec.loader.exec_module(module)
    finally:
        sys.modules.pop(spec.name, None)
    return module


def check_bundle(path: Path, source: type[Problem], target: type[Problem]) -> None:
    """The bundled classes must answer exactly like the library's."""
    text = path.read_text()
    leaked = [name for name in HIDDEN_NAMES if name in text]
    if leaked:
        raise ValueError(f"{path}: verifier-only details leaked into the bundle: {leaked}")
    module = load_bundle(path)
    for alias, problem in (("SOURCE", source), ("TARGET", target)):
        bundled = getattr(module, alias, None)
        if bundled is None or bundled.name != problem.name:
            raise ValueError(f"{path}: {alias} should be {problem.name}")
        instances = islice(problem.enumerate_instances(problem.exhaustive_scale), CHECKED_INSTANCES)
        for instance in instances:
            bundled.validate(instance)
            if bundled.is_yes(instance) != problem.is_yes(instance):
                raise ValueError(f"{path}: bundled {alias} disagrees on {instance}")


# --- The no-solver bundle ------------------------------------------------------

NOSOLVER_FILE = "problems_nosolver.py"

# Validation helpers copied into every no-solver bundle, in dependency order.
VALIDATION_HELPERS = {
    "base": ["InvalidInstance", "require", "is_int", "require_keys", "require_int",
             "validate_graph", "validate_cnf"],
    "graph_common": ["validate_plain_graph", "validate_graph_with_k"],
    "cnf_common": ["validate_three_literal_formula"],
    "sets_common": ["validate_set_system"],
    "numbers_common": ["validate_numbers"],
}

# Names that must never appear in a no-solver bundle.
FORBIDDEN_IN_NOSOLVER = (
    "exhaustive_scale", "check_problem",
    "is_yes", "random_instance", "enumerate_instances", "external_sat",
    "_satisfiable", "satisfiable(", "_dpll", "max_independent_set_size",
    "min_dominating_set_size", "three_colourable", "hamiltonian_path_exists",
    "hamiltonian_cycle_exists", "min_set_cover", "exact_cover_exists",
    "subset_sum_reachable",
)

NOSOLVER_HEADER = '''"""Problem definitions for this task: {source} -> {target}.

SOURCE = {source_class}: {source}, the problem you reduce FROM.
TARGET = {target_class}: {target}, the problem you reduce TO.

Each class docstring gives the exact instance format, yes-condition and edge
cases. Instances are plain dicts. Each class has one method:

    validate(instance)    raise InvalidInstance if the instance is malformed

This file does NOT provide solvers or instance generators. To check whether
two instances have the same answer, write your own from the definitions.

Generated by benchmark/make_task.py from the benchmark's problem library.
"""

from __future__ import annotations

from typing import Any
'''


def _lines(module: str, node: ast.AST) -> str:
    """Source lines of a top-level or nested definition, decorators included."""
    text, _ = _tree(module)
    starts = [node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])]
    lines = text.splitlines()[min(starts) - 1 : node.end_lineno]
    return "\n".join(lines)


def _top_level(module: str, name: str) -> str:
    _, tree = _tree(module)
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name == name:
            return _lines(module, node)
    raise ValueError(f"{name} not found in {module}.py")


def _spec_class(problem: type[Problem]) -> str:
    """The problem as a plain class: its docstring, name and validate()."""
    module = module_name(problem)
    _, tree = _tree(module)
    cls = next(
        n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == problem.__name__
    )
    docstring = cls.body[0]
    validate = next(
        n for n in cls.body if isinstance(n, ast.FunctionDef) and n.name == "validate"
    )
    return (
        f"class {problem.__name__}:\n"
        f"{_lines(module, docstring)}\n\n"
        f"    name = {problem.name!r}\n\n"
        f"{_lines(module, validate)}\n"
    )


def bundle_nosolver(source: type[Problem], target: type[Problem]) -> str:
    """problems.py for the no-solver setting: specs and validate() only."""
    parts = [
        NOSOLVER_HEADER.format(
            source=source.name, target=target.name,
            source_class=source.__name__, target_class=target.__name__,
        )
    ]
    for module, names in VALIDATION_HELPERS.items():
        parts.append(f"# {'-' * 70}\n# Validation helpers from benchmark/problems/{module}.py\n")
        parts.extend(_top_level(module, name) + "\n" for name in names)
    parts.append(f"# {'-' * 70}\n# The two problems\n")
    parts.append(_spec_class(source))
    parts.append(_spec_class(target))
    parts.append(f"SOURCE = {source.__name__}\nTARGET = {target.__name__}\n")
    return "\n\n".join(parts)


def check_nosolver_bundle(path: Path, source: type[Problem], target: type[Problem]) -> None:
    """Validation must match the library, and no solver may be reachable."""
    text = path.read_text()
    leaked = [name for name in FORBIDDEN_IN_NOSOLVER if name in text]
    if leaked:
        raise ValueError(f"{path}: solver code leaked into the no-solver bundle: {leaked}")
    module = load_bundle(path)
    for alias, problem in (("SOURCE", source), ("TARGET", target)):
        bundled = getattr(module, alias)
        if bundled.name != problem.name or bundled.__doc__ != problem.__doc__:
            raise ValueError(f"{path}: {alias} should be {problem.name} with its docstring")
        for instance in islice(problem.enumerate_instances(problem.exhaustive_scale), CHECKED_INSTANCES):
            bundled.validate(instance)
        try:
            bundled.validate({})
        except module.InvalidInstance:
            pass
        else:
            raise ValueError(f"{path}: {alias}.validate accepted an empty dict")


# --- Writing tasks --------------------------------------------------------------


def write_task(pair: Pair, tasks_dir: Path = TASKS_DIR) -> Path:
    source, target = PROBLEMS[pair.source], PROBLEMS[pair.target]
    descriptor = ReductionTask.model_validate(
        {
            "task_id": pair.task_id,
            "source_problem": source.name,
            "target_problem": target.name,
            "famous": pair.famous,
            "split": pair.split,
            "instructions": INSTRUCTIONS.format(source=source.name, target=target.name),
            "inputs": [{"name": "problems.py", "path": "inputs/problems.py"}],
        }
    )
    task_dir = tasks_dir / pair.task_id
    if task_dir.exists():
        shutil.rmtree(task_dir)
    (task_dir / "inputs").mkdir(parents=True)
    problems_file = task_dir / "inputs" / "problems.py"
    problems_file.write_text(bundle(source, target))
    (task_dir / "task.json").write_text(
        json.dumps(descriptor.model_dump(), indent=2) + "\n"
    )
    check_bundle(problems_file, source, target)
    nosolver_file = task_dir / "inputs" / NOSOLVER_FILE
    nosolver_file.write_text(bundle_nosolver(source, target))
    check_nosolver_bundle(nosolver_file, source, target)
    return task_dir


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("source", nargs="?", help="problem key, e.g. three_sat")
    parser.add_argument("target", nargs="?", help="problem key, e.g. clique")
    parser.add_argument("--all", action="store_true", help="build every pair in pairs.json")
    parser.add_argument("--list", action="store_true", help="list problem keys")
    parser.add_argument("--tasks", type=Path, default=TASKS_DIR)
    arguments = parser.parse_args(argv)

    if arguments.list:
        for key, problem in PROBLEMS.items():
            print(f"{key:18} {problem.name}")
        return
    try:
        pairs = load_pairs()
    except (OSError, ValueError) as error:
        parser.error(str(error))

    if arguments.all:
        selected = pairs
    elif arguments.source and arguments.target:
        selected = [p for p in pairs if (p.source, p.target) == (arguments.source, arguments.target)]
        if not selected:
            parser.error(
                f"{arguments.source} -> {arguments.target} is not in {PAIRS_FILE.name}; "
                "add it there first so its famous/split labels are recorded"
            )
    else:
        parser.error("give SOURCE TARGET, --all or --list")

    for pair in selected:
        try:
            write_task(pair, arguments.tasks)
        except ValueError as error:
            parser.error(str(error))
        print(f"wrote {pair.task_id}")

    if arguments.all:
        famous = sum(p.famous for p in pairs)
        dev = sum(p.split == "dev" for p in pairs)
        print(
            f"\n{len(pairs)} tasks: {famous} famous, {len(pairs) - famous} less common; "
            f"{dev} dev, {len(pairs) - dev} test"
        )
        known = {p.task_id for p in pairs}
        stale = sorted(
            d.name for d in arguments.tasks.iterdir()
            if d.is_dir() and d.name not in known
        ) if arguments.tasks.exists() else []
        for name in stale:
            print(f"note: tasks/{name} is not in {PAIRS_FILE.name}; delete it if obsolete")


if __name__ == "__main__":
    main()